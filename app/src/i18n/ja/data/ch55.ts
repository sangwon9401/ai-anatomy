export function ffn(x: number[], bend = true) {
  const pre = W1.map((w, i) => w.reduce((a, wk, k) => a + wk * x[k], B1[i]));
  const h = bend ? pre.map(gelu) : pre;
  const y = W2.map((w) => w.reduce((a, wj, j) => a + wj * h[j], 0));
  return { pre, h, y, out: x.map((v, k) => v + y[k]) };
}

